//! Дежурство на узле связи: кот сидит у рации и прибавляет силы отряду в поле
//! (§12.60).
//!
//! # Зачем это отдельная задача
//!
//! §12.59 сделал узел лицензией-слотом: сколько узлов, столько вылазок. Сам по
//! себе узел при этом ничего не делал — стоял и считался. Дежурство даёт ему
//! второй смысл и заводит **первое место, где кот на базе влияет на исход
//! вылазки**: до сих пор всё, что решало исход, уходило вместе с отрядом.
//!
//! # Садится только приписанный (§12.76)
//!
//! Дежурство раздаётся **не как работа, а как приписка**: `assign_relay` берёт
//! только тех, кого игрок сам посадил к рации (`Posted`), и ведёт каждого
//! ровно на свой узел. Свободного кота «из простоя» он не зовёт больше никогда.
//!
//! До §12.76 было наоборот: узел звал любого, кому ничего не досталось, — и на
//! базе из трёх котов это значило, что ушедший в поле отряд забирал ещё одного,
//! а стройка вставала. «Простоя», из которого брался бонус, у маленькой базы
//! нет: у неё каждый кот — это работа, которую больше некому сделать.
//!
//! Приписка — **конфигурация, а не задача**, и в этом весь смысл её сохранения:
//! голод и сон снимают `OnDuty`, но не `Posted`, и раздатчик вернёт кота к
//! рации, как только тот освободится. Разовая посадка повторила бы дыру парты —
//! игрок кликнул, кот поел и больше не вернулся, — а пропажу связи видно только
//! просевшим бонусом на возвращении, то есть поздно.
//!
//! # Место в порядке раздатчиков — предпоследнее
//!
//! `assign_relay` стоит перед `assign_nap` и после всех работ. С §12.76 это уже
//! не про «бонус из простоя»: приписанный кот попадёт к рации из любого места
//! очереди, потому что зовут именно его. Место осталось прежним потому, что
//! приписка не должна отменять нужду: голодного, раненого и валящегося с лап
//! успевают забрать раздатчики до неё, и связь ждёт, пока он поест и выспится.
//!
//! **Но раз сел — сидит.** Появившийся чертёж дежурного не срывает: занятость в
//! этом проекте это набор фильтров, и `OnDuty` попадает в них наравне с
//! остальными одиннадцатью задачами (инвариант 7). Вводить для этого ничего не
//! пришлось — исключением была ровно дремота, у которой своего компонента нет и
//! быть не должно (§12.52).
//!
//! # Связь считается за тик, а не на возвращении
//!
//! Каждый тик, пока отряд в поле и на его узле сидит дежурный, в `Mission`
//! падает вклад — «сила узла плюс уровень связиста». На возвращении это делится
//! на длину вылазки, то есть бонус пропорционален **доле времени со связью**.
//!
//! Мерить связь одним замером нельзя ни на уходе, ни на возвращении: в первом
//! случае хватило бы посадить кота на тик, во втором бонус повис бы на том, кто
//! случайно оказался у рации в последний тик, — а это уже не решение игрока, а
//! расписание. Делить приходится потому, что иначе длинная вылазка копила бы
//! бонус просто длиной.

use bevy_ecs::prelude::*;

use crate::components::*;
use crate::map::BaseMap;
use crate::path::Reach;
use crate::skills::{SKILL_RELAY, level_of};

/// Все клетки раций карты, в порядке обхода: он фиксирован, значит и очередь
/// свободных мест детерминирована (§11). Близнец `missions::gate_cells`.
pub(crate) fn relay_cells<'a>(
    map: &'a BaseMap,
    rules: &'a TileRules,
) -> impl Iterator<Item = (i32, i32)> + 'a {
    (0..map.height)
        .flat_map(move |y| (0..map.width).map(move |x| (x, y)))
        .filter(move |&(x, y)| rules.is_relay_node(map.tile_at(x, y)))
}

/// Вклад связиста в силу отряда за один тик дежурства (§12.60).
///
/// Сила самого узла (`relay` у тайла) плюс уровень «Связи» дежурного: рация
/// работает и без мастера, но мастер выжимает из неё больше. Домен здесь свой,
/// а не «Вылазка», намеренно — см. `SKILL_RELAY`.
pub(crate) fn duty_gain(
    tiles: &TileRules,
    map: &BaseMap,
    skill_rules: &SkillRules,
    skills: Option<&Skills>,
    spot: (i32, i32),
) -> i32 {
    let power = tiles.comms_of(map.tile_at(spot.0, spot.1));
    if power <= 0 {
        return 0;
    }
    let level = skill_rules
        .index_of(SKILL_RELAY)
        .map_or(0, |s| level_of(skill_rules, skills, s));
    power + level
}

/// На сколько процентов связь ускоряет дорогу прямо сейчас (§12.277): по
/// [`ROAD_STEP`] за очко дежурства, но не быстрее чем вдвое.
///
/// Связь режет **путь, а не работу**: отряд идёт по подсказкам из эфира, а
/// копать на месте за него никто не будет. Зовут двое — `run_missions` (сам
/// срез) и снимок (подпись у рации), — и разойтись им нельзя (инвариант 14).
pub(crate) fn road_boost(duty_total: i32) -> i32 {
    (duty_total * ROAD_STEP).clamp(0, 100)
}

/// Сколько процентов скорости дороги даёт очко дежурства (§12.277): рация
/// с силой 1 и связист без навыка — четверть, «Связь» 3 — вдвое.
pub(crate) const ROAD_STEP: i32 = 25;

/// Сажает **приписанного** кота к рации того узла, чей отряд сейчас в поле.
///
/// С §12.76 раздачи здесь нет: раздатчик перебирает не свободных котов, а
/// приписки игрока (`Posted`), и каждого ведёт только на его собственный узел.
/// Никого не приписали — эфир пустой, и это законное состояние: вылазка уходит
/// без бонуса связи, как уходила до §12.60.
///
/// **Предпоследний раздатчик** (§12.60): голод, раны и сон разбирают котов
/// раньше, и приписка их не отменяет — связь подождёт, пока связист поест.
/// Дремота идёт после — она раздаёт не работу, а её отсутствие (§12.52).
///
/// Узел просит кота, **только пока его вылазка в поле**: дежурство — первая
/// задача без естественного конца, и без этого условия кот сидел бы у рации с
/// пустым эфиром до скончания партии. Оно же снимает задачу, когда отряд
/// вернулся: искать, где ещё её снять, не приходится.
///
/// Ничью решает `id` кота, как во всех раздатчиках (инвариант 9): порядок
/// обхода сущностей ECS зависит от истории вставок и недетерминирован.
pub(crate) fn assign_relay(
    map: Res<BaseMap>,
    tiles: Res<TileRules>,
    mut commands: Commands,
    missions: Query<(Entity, &Mission)>,
    // Кто уже сидит: занятость держит сам `OnDuty`, отдельного реестра нет —
    // ровно как у лежанки (`Rest::spot`) и станка (`Craft::cell`, §12.96).
    posted: Query<(Entity, &OnDuty, Option<&Posted>)>,
    free_cats: Query<
        (Entity, &UnitId, &Position, &Posted),
        (
            Without<Assignment>,
            Without<Haul>,
            Without<Rest>,
            Without<Study>,
            Without<Researching>,
            Without<Crafting>,
            Without<Equipping>,
            Without<Eating>,
            Without<Healing>,
            Without<Treating>,
            Without<Squad>,
            Without<OnDuty>,
            Without<Away>,
            Without<Path>,
        ),
    >,
) {
    // Кому помогать (§12.278, §12.285): связь именная — радист приписан к
    // **столу** отряда и нужен, только пока у этого отряда есть вылазка, уже
    // на сборе: отряд ждёт своего радиста и без него не уходит.
    let away_nodes: Vec<(i32, i32)> = missions.iter().map(|(_, m)| m.node).collect();

    // Рации, на которых дежурство **что-то даёт**. Нулевой `comms` значит
    // «дежурить незачем», и кота сюда не зовут: гонять его к рации, от которой
    // нет пользы, — это отнятое котовремя без отдачи. Тем же нулём механика
    // выключена в синтетических схемах, как выключены навыки, рынок и цели.
    // Рация отрядом не владеет (§12.285): радист садится за любую свободную.
    let radios: Vec<(i32, i32)> = relay_cells(&map, &tiles)
        .filter(|&(x, y)| tiles.comms_of(map.tile_at(x, y)) > 0)
        .collect();

    // Кто сидит зря: вылазки его отряда больше нет, рацию снесли или приписку
    // сняли. Снимаем сразу — это и есть конец задачи, второго места для него
    // заводить не надо. С §12.76 `Posted` — единственная причина сидеть у
    // рации, поэтому она же и единственный признак «сидит по делу».
    let mut evicted: Vec<Entity> = Vec::new();
    for (cat_e, duty, post) in &posted {
        let gone = !radios.contains(&duty.spot);
        let needed = post.is_some_and(|p| away_nodes.contains(&p.spot));
        if gone || !needed {
            commands.entity(cat_e).remove::<OnDuty>();
            evicted.push(cat_e);
        }
    }

    let taken: Vec<(i32, i32)> = posted
        .iter()
        .filter(|(e, ..)| !evicted.contains(e))
        .map(|(_, d, _)| d.spot)
        .collect();
    let mut open: Vec<(i32, i32)> = radios
        .iter()
        .copied()
        .filter(|spot| !taken.contains(spot))
        .collect();
    if open.is_empty() {
        return;
    }

    // Приписанные, по `id` (инвариант 9): первым выбирает рацию тот, кто
    // раньше по `id`, а ближайшую — по дороге (§12.14).
    let mut idle: Vec<(&str, Entity, (i32, i32), (i32, i32))> = free_cats
        .iter()
        .filter(|(.., post)| away_nodes.contains(&post.spot))
        .map(|(e, id, p, post)| (id.0.as_str(), e, (p.x, p.y), post.spot))
        .collect();
    idle.sort_unstable_by_key(|&(id, ..)| id);

    for (_, cat_e, at, _) in idle {
        if open.is_empty() {
            return;
        }
        let reach = Reach::all(&map, &tiles, at);
        let picked = open
            .iter()
            .enumerate()
            .filter_map(|(i, s)| reach.dist_at(s.0, s.1).map(|d| (d, s.1, s.0, i)))
            .min();
        let Some((.., i)) = picked else { continue };
        let spot = open.remove(i);
        let path = reach.path_to(spot.0, spot.1).unwrap_or_default();
        commands
            .entity(cat_e)
            .insert((OnDuty { spot }, Path { steps: path }));
    }
}
