//! Участки внешнего мира и очаги на них (§12.198).
//!
//! Это **второй источник событий без инициатора** после таймлайна (§12.28), и
//! разница между ними одна: у события есть дата, а у очага — соседи.
//! Расписание называет, **когда**; очаг — **куда**. До §12.198 бездействие
//! игрока не стоило ничего: вылазка была добровольным доходом, и мир, пока его
//! не трогали, стоял.
//!
//! Механики здесь три, и все они видны игроку вперёд:
//!   * **рост** — каждые `grows` тиков ступень очага поднимается до предела;
//!   * **расползание** — на пределе тот же счётчик сажает очаг той же породы на
//!     первого чистого соседа по порядку `links`;
//!   * **цена бездействия** — заражённый участок закрывает свои заказы.
//!
//! Ни одна из трёх не бросает кубик и ничего не прячет: «станет ступенью 3
//! через 240» и «расползётся на Старые шахты» обязаны быть написаны **до**
//! того, как игрок решил не идти, — иначе планируемая игра превращается в
//! наказание за незнание (§12.23, §12.44, §12.80).
//!
//! Своей сущности у очага нет: ни позиции на карте базы, ни компонентов, ни
//! владельца — это состояние мира по индексу участка, ресурс `Blights`. Тот же
//! довод, по которому его не получили `Fame`, `Techs` и `Standing`.

use bevy_ecs::prelude::*;

use crate::components::*;

/// Что случится с очагом на следующем шаге счётчика (§12.198).
///
/// Считается **ядром и одним выражением** на снимок и на саму систему роста:
/// разойдись они, карта обещала бы «расползётся на Свалку», а очаг сел бы на
/// Ржавую дорогу — ровно то, что запрещает инвариант 14.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub(crate) enum Step {
    /// Поднимется до этой ступени.
    Grow(i32),
    /// Расползётся на этот участок.
    Spread(usize),
    /// Дальше некуда: предел ступени, а расползаться нечем или некуда.
    Held,
}

/// Первый чистый сосед по порядку `links` — то есть куда очаг пойдёт.
///
/// Порядок рулсета, а не расстояние и не случайность: расползание обязано быть
/// **предсказуемым**, иначе игрок не может встать у него на пути, и вся карта
/// вырождается в налог (§12.198).
fn free_neighbour(sites: &SiteRules, blights: &Blights, site: usize) -> Option<usize> {
    sites
        .0
        .get(site)?
        .links
        .iter()
        .copied()
        .find(|&n| blights.at(n).is_none())
}

/// Что будет на следующем шаге и через сколько тиков.
///
/// `None` — очага нет или он не растёт вовсе (`grows: 0`): у стоячего очага
/// следующего шага не существует, и показывать таймер, который никогда не
/// дотикает, значило бы обещать событие.
pub(crate) fn next_step(
    rules: &BlightRules,
    sites: &SiteRules,
    blights: &Blights,
    site: usize,
) -> Option<(Step, u64)> {
    let blight = blights.at(site)?;
    let rule = rules.0.get(blight.def)?;
    if rule.grows == 0 {
        return None;
    }
    let step = if blight.stage < rules.top_stage(blight.def) {
        Step::Grow(blight.stage + 1)
    } else if rule.spreads {
        match free_neighbour(sites, blights, site) {
            Some(n) => Step::Spread(n),
            None => Step::Held,
        }
    } else {
        Step::Held
    };
    Some((step, rule.grows.saturating_sub(blight.age)))
}

/// Растит и расползает очаги — единственная система модуля.
///
/// Стоит после `run_timeline` (§12.198): расписание сеет, карта растит, и
/// посеянный в этом тике очаг начинает свой счёт со следующего — как заказ,
/// заведённый `plan_craft`, получает мастера тем же тиком, но работу считает со
/// следующего.
///
/// Обход — **по индексу участка**, и это не вкус: расползание сажает очаг на
/// соседа, а тот может стоять и раньше по списку, и позже. Порядок обхода —
/// единственное, что делает результат воспроизводимым (§11).
///
/// Цепочки за один тик не бывает: у посеянного очага `age == 0`, а шаг требует
/// `age >= grows`. Расползание идёт по шагу за раз — очаг захватывает карту
/// со скоростью `grows`, а не мгновенно.
pub(crate) fn grow_blights(
    rules: Res<BlightRules>,
    sites: Res<SiteRules>,
    mut blights: ResMut<Blights>,
) {
    for site in 0..blights.0.len() {
        let Some(mut blight) = blights.at(site) else {
            continue;
        };
        let Some(rule) = rules.0.get(blight.def) else {
            continue;
        };
        if rule.grows == 0 {
            continue;
        }
        // Счёт вверх, до порога и не дальше: очаг, которому некуда расти,
        // стоит на пороге, а не копит тики в пустоту. Иначе `next_step`
        // показывал бы отрицательный срок у застрявшего очага.
        blight.age = (blight.age + 1).min(rule.grows);
        if blight.age < rule.grows {
            blights.0[site] = Some(blight);
            continue;
        }
        match next_step(&rules, &sites, &blights, site).map(|(step, _)| step) {
            Some(Step::Grow(stage)) => {
                blight.stage = stage;
                blight.age = 0;
            }
            Some(Step::Spread(to)) => {
                blights.seed(to, blight.def);
                blight.age = 0;
            }
            // Дальше некуда — счётчик стоит на пороге. Освободится сосед, и
            // очаг тронется тем же тиком: ждать полный круг заново он не
            // обязан, ведь всё это время он был готов.
            _ => {}
        }
        blights.0[site] = Some(blight);
    }
}

/// Насколько тяжелее зачистка заражённого участка (§12.198).
///
/// Прибавка к сложности заказа, а не множитель: множитель на `danger: 0`
/// не значил бы ничего — а «уборка мусора, но заражённая» обязана быть тяжелее
/// уборки мусора. Общее правило нулей при этом цело: `danger: 0` у **породы**
/// выключает лестницу.
pub(crate) fn stage_danger(rules: &BlightRules, blight: Option<Blight>) -> i32 {
    match blight {
        Some(b) => rules.0.get(b.def).map_or(0, |r| r.danger * b.stage),
        None => 0,
    }
}

/// Открыт ли заказ по своему месту (§12.198): участок, на котором он стоит,
/// не заражён.
///
/// Заказ **без места** не закрывается никогда: вылазка за своим идёт за котом,
/// а не в точку, и запирать её картой значило бы сделать плен необратимым
/// (§12.40).
pub(crate) fn site_is_clear(blights: &Blights, site: Option<usize>) -> bool {
    match site {
        Some(s) => blights.at(s).is_none(),
        None => true,
    }
}

/// Участки, на которых стоит этот заказ на зачистку, — от самого запущенного к
/// самому свежему, при равной ступени по порядку участков.
///
/// Порядок здесь не украшение: по нему правило автовылазки выбирает цель
/// (§12.198), а панель показывает список. Считается **одним выражением** на
/// обоих, иначе правило ушло бы не туда, куда показала карта (инвариант 14).
pub(crate) fn targets_of(rules: &MissionRules, blights: &Blights, def: usize) -> Vec<usize> {
    let Some(cleanses) = rules.0.get(def).and_then(|m| m.cleanses) else {
        return Vec::new();
    };
    let mut found: Vec<(i32, usize)> = blights
        .0
        .iter()
        .enumerate()
        .filter_map(|(site, slot)| match slot {
            Some(b) if b.def == cleanses => Some((-b.stage, site)),
            _ => None,
        })
        .collect();
    found.sort_unstable();
    found.into_iter().map(|(_, site)| site).collect()
}

/// Куда пойдёт заявка: названный игроком участок, а если он не назван — место
/// самого заказа (§12.198).
///
/// Одно выражение на заявку игрока, на правило автовылазки и на прогноз в
/// панели: «куда идёт этот отряд» обязано отвечаться одинаково всем троим.
/// `site < 0` в команде значит «не назван» — заказ на зачистку в этом случае
/// сам берёт самый запущенный очаг, обычный заказ идёт к себе домой.
pub(crate) fn aim_of(
    rules: &MissionRules,
    blights: &Blights,
    def: usize,
    asked: Option<usize>,
) -> Option<usize> {
    let rule = rules.0.get(def)?;
    if rule.cleanses.is_none() {
        return rule.site;
    }
    let targets = targets_of(rules, blights, def);
    match asked {
        Some(site) if targets.contains(&site) => Some(site),
        Some(_) => None,
        None => targets.first().copied(),
    }
}

/// Насколько тяжелее будет **этому заказу** там, куда он пойдёт (§12.198).
///
/// Одно выражение на три вызывающих: возвращение отряда (`run_missions`),
/// прогноз узла в штабе и снимок. Разойдись они — панель обещала бы сложность
/// свежего очага, а отряд встретил бы запущенный (инвариант 14).
///
/// У идущей вылазки цель **заморожена** (`Mission::site`), а ступень берётся
/// свежая: отряд встретит то, что успело вырасти, пока он шёл, — в этом и
/// состоит цена промедления.
pub(crate) fn aim_danger(
    missions: &MissionRules,
    rules: &BlightRules,
    blights: &Blights,
    def: usize,
    asked: Option<usize>,
) -> i32 {
    let site = aim_of(missions, blights, def, asked);
    stage_danger(rules, site.and_then(|s| blights.at(s)))
}
